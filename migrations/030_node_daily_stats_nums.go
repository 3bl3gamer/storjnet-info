package main

import "github.com/go-pg/migrations/v8"

// node_daily_stats kept raw 32-byte node IDs in its arrays: almost random, so incompressible,
// and it was the largest table. Now the arrays hold node_nums.num, a small integer per node ID.
//
// The table is rebuilt into a new one and swapped at the end, so it can be read all the time,
// but it can not be written (by stat-nodes) while the migration is running.
func init() {
	migrations.MustRegisterTx(func(db migrations.DB) error {
		return execSome(db, `
			LOCK TABLE storjnet.node_daily_stats IN SHARE MODE;

			CREATE TABLE storjnet.node_nums (
				num integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				node_id bytea NOT NULL UNIQUE,
				CHECK (length(node_id) = 32)
			);

			-- Numbered in order of appearance (as it will go on later): the nodes active on the same day
			-- get close numbers, and sorted arrays of those are compressed better by the filesystem.
			-- IDs are taken from the stats too, in case some of them are not in nodes.
			INSERT INTO storjnet.node_nums (num, node_id)
			SELECT row_number() OVER (ORDER BY COALESCE(n.created_at, s.first_date::timestamptz), node_id), node_id
			FROM (SELECT id AS node_id, created_at FROM storjnet.nodes) AS n
			FULL OUTER JOIN (
				SELECT node_id, min(date) AS first_date
				FROM (
					SELECT date, unnest(node_ids || come_node_ids || left_node_ids) AS node_id
					FROM storjnet.node_daily_stats
				) AS t
				GROUP BY node_id
			) AS s USING (node_id);

			SELECT setval(
				pg_get_serial_sequence('storjnet.node_nums', 'num'),
				(SELECT max(num) FROM storjnet.node_nums)
			);
			ANALYZE storjnet.node_nums;

			-- Constraints are named explicitly, otherwise they would keep "_new" in their names.
			-- The checks forbid NULL elements: those would mean a node ID without a number.
			CREATE TABLE storjnet.node_daily_stats_new (
				date date CONSTRAINT node_daily_stats_date_not_null NOT NULL,
				kind text CONSTRAINT node_daily_stats_kind_not_null NOT NULL,
				node_ids integer[] CONSTRAINT node_daily_stats_node_ids_not_null NOT NULL,
				come_node_ids integer[] CONSTRAINT node_daily_stats_come_node_ids_not_null NOT NULL,
				left_node_ids integer[] CONSTRAINT node_daily_stats_left_node_ids_not_null NOT NULL,
				CONSTRAINT node_daily_stats_node_ids_check CHECK (array_position(node_ids, NULL) IS NULL),
				CONSTRAINT node_daily_stats_come_node_ids_check CHECK (array_position(come_node_ids, NULL) IS NULL),
				CONSTRAINT node_daily_stats_left_node_ids_check CHECK (array_position(left_node_ids, NULL) IS NULL)
			);

			INSERT INTO storjnet.node_daily_stats_new (date, kind, node_ids, come_node_ids, left_node_ids)
			SELECT date, kind,
				(
					SELECT COALESCE(array_agg(n.num ORDER BY n.num), '{}')
					FROM unnest(s.node_ids) AS id LEFT JOIN storjnet.node_nums AS n ON n.node_id = id
				), (
					SELECT COALESCE(array_agg(n.num ORDER BY n.num), '{}')
					FROM unnest(s.come_node_ids) AS id LEFT JOIN storjnet.node_nums AS n ON n.node_id = id
				), (
					SELECT COALESCE(array_agg(n.num ORDER BY n.num), '{}')
					FROM unnest(s.left_node_ids) AS id LEFT JOIN storjnet.node_nums AS n ON n.node_id = id
				)
			FROM storjnet.node_daily_stats AS s
			ORDER BY date, kind;

			DROP TABLE storjnet.node_daily_stats;
			ALTER TABLE storjnet.node_daily_stats_new RENAME TO node_daily_stats;
			ALTER TABLE storjnet.node_daily_stats ADD PRIMARY KEY (date, kind);
			`)
	}, func(db migrations.DB) error {
		return execSome(db, `
			LOCK TABLE storjnet.node_daily_stats IN SHARE MODE;

			-- the checks are temporary (a number without a node ID would become NULL), 009 has none
			CREATE TABLE storjnet.node_daily_stats_old (
				date date CONSTRAINT node_daily_stats_date_not_null NOT NULL,
				kind text CONSTRAINT node_daily_stats_kind_not_null NOT NULL,
				node_ids bytea[] CONSTRAINT node_daily_stats_node_ids_not_null NOT NULL,
				come_node_ids bytea[] CONSTRAINT node_daily_stats_come_node_ids_not_null NOT NULL,
				left_node_ids bytea[] CONSTRAINT node_daily_stats_left_node_ids_not_null NOT NULL,
				CONSTRAINT tmp_node_ids_check CHECK (array_position(node_ids, NULL) IS NULL),
				CONSTRAINT tmp_come_node_ids_check CHECK (array_position(come_node_ids, NULL) IS NULL),
				CONSTRAINT tmp_left_node_ids_check CHECK (array_position(left_node_ids, NULL) IS NULL)
			);

			INSERT INTO storjnet.node_daily_stats_old (date, kind, node_ids, come_node_ids, left_node_ids)
			SELECT date, kind,
				(
					SELECT COALESCE(array_agg(n.node_id ORDER BY n.node_id), '{}')
					FROM unnest(s.node_ids) AS x LEFT JOIN storjnet.node_nums AS n ON n.num = x
				), (
					SELECT COALESCE(array_agg(n.node_id ORDER BY n.node_id), '{}')
					FROM unnest(s.come_node_ids) AS x LEFT JOIN storjnet.node_nums AS n ON n.num = x
				), (
					SELECT COALESCE(array_agg(n.node_id ORDER BY n.node_id), '{}')
					FROM unnest(s.left_node_ids) AS x LEFT JOIN storjnet.node_nums AS n ON n.num = x
				)
			FROM storjnet.node_daily_stats AS s
			ORDER BY date, kind;

			ALTER TABLE storjnet.node_daily_stats_old
				DROP CONSTRAINT tmp_node_ids_check,
				DROP CONSTRAINT tmp_come_node_ids_check,
				DROP CONSTRAINT tmp_left_node_ids_check;

			DROP TABLE storjnet.node_daily_stats;
			ALTER TABLE storjnet.node_daily_stats_old RENAME TO node_daily_stats;
			ALTER TABLE storjnet.node_daily_stats ADD PRIMARY KEY (date, kind);

			DROP TABLE storjnet.node_nums;
			`)
	})
}
